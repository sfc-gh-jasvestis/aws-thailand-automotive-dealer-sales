FROM RAW.CUSTOMER_PROFILES f
JOIN RAW.THAI_AUTO_MARKET e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

