SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_INVENTORY_DAYS <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
